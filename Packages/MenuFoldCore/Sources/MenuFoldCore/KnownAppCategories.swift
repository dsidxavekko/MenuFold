import Foundation

extension AppCategory {
    /// Automatic category of an app: its Info.plist category, else a built-in table of well-known
    /// bundle ids / prefixes, else `.other`.
    ///
    /// Many popular apps (and several Apple ones) ship without `LSApplicationCategoryType`, which
    /// would pile them all into "Інше". The developer's own category still wins whenever it maps to
    /// a known one, since it is the more deliberate choice.
    public static func automatic(for app: AppEntry) -> AppCategory {
        let fromInfo = from(raw: app.infoCategory)
        if fromInfo.id != otherID { return fromInfo }
        return known(bundleID: app.id) ?? .other
    }

    /// The category from `KnownApps` for a bundle id (case-insensitive): an exact entry first, then
    /// the longest matching prefix rule. nil when the id is unknown.
    static func known(bundleID: String) -> AppCategory? {
        let id = bundleID.lowercased()
        let short = KnownApps.byBundleID[id]
            ?? KnownApps.byPrefix.filter { id.hasPrefix($0.prefix) }.max { $0.prefix.count < $1.prefix.count }?.category
        guard let short else { return nil }
        let category = from(raw: "public.app-category." + short)
        return category.id == otherID ? nil : category
    }
}

